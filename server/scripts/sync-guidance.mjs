// Copies the styling guidance in docs/styling/ into the Worker, which can't read files at runtime.
//   node scripts/sync-guidance.mjs          writes src/guidance.ts
// test/guidance.test.ts fails when the two drift apart.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

export function guidanceSource() {
  const read = (name) =>
    readFileSync(fileURLToPath(new URL(`../../docs/styling/${name}`, import.meta.url)), "utf8").replace(/\r\n/g, "\n");
  // Drop the skill's front matter; agents get the body.
  const skill = read("SKILL.md").replace(/^---\n[\s\S]*?\n---\n/, "").trim();
  const text = `${skill}\n\n---\n\n${read("principles.md").trim()}\n\nSources: docs/styling/sources.md in the Putia repository.\n`;
  return `// Generated by scripts/sync-guidance.mjs from docs/styling/. Do not edit by hand.\nexport const STYLING_GUIDANCE = ${JSON.stringify(text)};\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(fileURLToPath(new URL("../src/guidance.ts", import.meta.url)), guidanceSource());
  console.log("Wrote src/guidance.ts");
}
